import numpy as np
import matplotlib.pyplot as plt
from pathlib import Path
from scipy.integrate import solve_ivp

# ------------------------------------------------------------
# State-pair continuum-radiation model
# ------------------------------------------------------------
# User equation:
#   i*hbar d_t Psi1 + (hbar^2/m) d_x^2 Psi1
# + i*hbar d_t Psi2 + Fhat*xhat Psi2 = 0
#
# Candidate operator-valued radiative realization:
#   xhat = x0(a+a^dagger)
#   Fhat = (hbar/x0) sum_k g_k[1+eta S(t)](b_k+b_k^dagger)
# so that, after the rotating-wave approximation,
#   Fhat*xhat -> hbar sum_k g_k[1+eta S(t)]
#                  (a b_k^dagger + a^dagger b_k).
#
# Psi1 = |1>_osc |chi_ext> |vac>_gamma.
# Psi2 = c_e |1,vac> + sum_k c_k |0,1_k>, with the external
# wavefunction implicit in the effective overlap S(t).
#
# There is NO nonradiative bath in this script. Thus every completed
# decay produces one photon in the continuum.

OUT = Path('/mnt/data/state_pair_radiative_decay_outputs')
OUT.mkdir(exist_ok=True)

HBAR = 1.0
OMEGA0 = 1.0
MASS = 1.0
X0 = np.sqrt(HBAR/(2*MASS*OMEGA0))

# Radiation continuum
NMODES = 501
WMIN, WMAX = 0.40, 1.60
wk = np.linspace(WMIN, WMAX, NMODES)
dw = wk[1] - wk[0]
GAMMA0 = 0.010                     # isolated Markov decay rate
J0 = GAMMA0/(2*np.pi)
gk = np.sqrt(J0*dw) * np.ones_like(wk)

# External incoming Gaussian wavefunction versus localized oscillator
SIGMA_OSC = 1.0
SIGMA_EXT = 1.5
Y0 = 15.0
VEXT = 0.60
TCOLL = Y0/VEXT
ETA = 6.0

def overlap_S(t):
    # normalized modulus of overlap of two Gaussian wavefunctions
    d = Y0 - VEXT*t
    return np.exp(-(d*d)/(4*(SIGMA_OSC**2 + SIGMA_EXT**2)))

def coupling_multiplier(t, encounter):
    return 1.0 + (ETA*overlap_S(t) if encounter else 0.0)

# Exact finite-continuum single-excitation dynamics.
# y = [c_e, c_1, ..., c_N].
def rhs(t, y, encounter):
    ce = y[0]
    ck = y[1:]
    f = coupling_multiplier(t, encounter)
    dce = -1j*(OMEGA0*ce + np.dot(gk*f, ck))
    dck = -1j*(wk*ck + gk*f*ce)
    return np.concatenate(([dce], dck))

Y0V = np.zeros(NMODES+1, dtype=complex)
Y0V[0] = 1.0
TMAX = 120.0
T_EVAL = np.linspace(0.0, TMAX, 1201)

def solve_case(encounter):
    sol = solve_ivp(lambda t,y: rhs(t,y,encounter), (0.0,TMAX), Y0V,
                    t_eval=T_EVAL, rtol=2e-8, atol=2e-10, method='DOP853')
    Y = sol.y.T
    Pe = np.abs(Y[:,0])**2
    Pg = np.sum(np.abs(Y[:,1:])**2, axis=1)
    return Y, Pe, Pg, Pe+Pg

Yspace, Pe_space, Pg_space, norm_space = solve_case(False)
Yenc, Pe_enc, Pg_enc, norm_enc = solve_case(True)

# Markov / Wigner-Weisskopf approximation from the same spectral density.
def markov_survival(encounter):
    f = np.array([coupling_multiplier(t, encounter) for t in T_EVAL])
    gamma = GAMMA0*f*f
    integ = np.zeros_like(T_EVAL)
    integ[1:] = np.cumsum(0.5*(gamma[1:]+gamma[:-1])*np.diff(T_EVAL))
    return np.exp(-integ), gamma

PeM_space, gamma_space = markov_survival(False)
PeM_enc, gamma_enc = markov_survival(True)

def cross_time(P, level=np.exp(-1)):
    idx = np.where(P <= level)[0]
    if len(idx)==0:
        return np.nan
    i = idx[0]
    if i == 0:
        return float(T_EVAL[0])
    t0,t1 = T_EVAL[i-1],T_EVAL[i]
    p0,p1 = P[i-1],P[i]
    return float(t0 + (level-p0)*(t1-t0)/(p1-p0))

tau_space = cross_time(Pe_space)
tau_enc = cross_time(Pe_enc)
tauM_space = cross_time(PeM_space)
tauM_enc = cross_time(PeM_enc)

def spectrum_metrics(Yfinal):
    pk = np.abs(Yfinal[1:])**2
    P = pk.sum()
    mean = np.sum(wk*pk)/P
    std = np.sqrt(np.sum((wk-mean)**2*pk)/P)
    return pk, float(mean), float(std)

spec_space, meanw_space, stdw_space = spectrum_metrics(Yspace[-1])
spec_enc, meanw_enc, stdw_enc = spectrum_metrics(Yenc[-1])

# Plots
Svals = np.array([overlap_S(t) for t in T_EVAL])
fig, ax = plt.subplots(1,2,figsize=(12,4.5))
ax[0].plot(T_EVAL,Svals)
ax[0].axvline(TCOLL,ls='--',label='wavepacket centers meet')
ax[0].set(xlabel='time',ylabel='overlap S(t)',title='External wavefunction overlap')
ax[0].legend()
ax[1].plot(T_EVAL,gamma_space,label='space')
ax[1].plot(T_EVAL,gamma_enc,label='external encounter')
ax[1].set(xlabel='time',ylabel='Gamma(t)',title='Radiative rate generated by Fx coupling')
ax[1].legend()
fig.tight_layout(); fig.savefig(OUT/'01_overlap_and_rate.png',dpi=180); plt.close(fig)

fig, ax = plt.subplots(figsize=(8,5))
ax.plot(T_EVAL,Pe_space,label='space: exact continuum')
ax.plot(T_EVAL,PeM_space,'--',label='space: Markov')
ax.plot(T_EVAL,Pe_enc,label='encounter: exact continuum')
ax.plot(T_EVAL,PeM_enc,'--',label='encounter: Markov')
ax.axhline(np.exp(-1),ls=':',label='1/e')
ax.axvline(TCOLL,ls=':',label='external packet center')
ax.set(xlabel='time',ylabel='excited-state probability',title='Excited harmonic-oscillator decay')
ax.legend(fontsize=8)
fig.tight_layout(); fig.savefig(OUT/'02_excited_state_decay.png',dpi=180); plt.close(fig)

fig, ax = plt.subplots(figsize=(8,5))
ax.plot(T_EVAL,Pg_space,label='space photon probability')
ax.plot(T_EVAL,Pg_enc,label='encounter photon probability')
ax.set(xlabel='time',ylabel='one-photon probability',title='Energy transferred to radiation continuum')
ax.legend()
fig.tight_layout(); fig.savefig(OUT/'03_photon_probability.png',dpi=180); plt.close(fig)

fig, ax = plt.subplots(figsize=(8,5))
ax.plot(wk,spec_space/spec_space.sum(),label=f'space; mean omega={meanw_space:.4f}')
ax.plot(wk,spec_enc/spec_enc.sum(),label=f'encounter; mean omega={meanw_enc:.4f}')
ax.axvline(OMEGA0,ls='--',label='oscillator omega0')
ax.set(xlabel='photon angular frequency',ylabel='conditional probability',title='Emitted photon spectrum')
ax.legend()
fig.tight_layout(); fig.savefig(OUT/'04_photon_spectrum.png',dpi=180); plt.close(fig)

# data + report
arr = np.column_stack([T_EVAL,Svals,Pe_space,Pe_enc,Pg_space,Pg_enc,PeM_space,PeM_enc,norm_space,norm_enc])
